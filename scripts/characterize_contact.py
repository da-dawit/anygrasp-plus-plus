"""Step 1b: the grid pad under non-ideal grasps. Each case changes one thing a real detector or object would,
and compares slip onset (1 deg) and failure (10 deg) with the patch prediction from the pad points that actually
touch. Prediction band = [onset at the lift's peak acceleration, static onset].

    python scripts/characterize_contact.py [--contact rubber|rigid]
Outputs: results/calib/characterize_<contact>.csv, characterize_<contact>.tex
"""
import csv
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import argparse  # noqa: E402
from anygrasp_pp.contact_rig import X_HIDDEN, grid_points, CONTACT, RIGID_CONTACT  # noqa: E402
from anygrasp_pp.physics import patch_dstar, MASS  # noqa: E402
from anygrasp_pp.rig_trial import bisect_onset, a_peak, LIFT_H, LIFT_T, TWIST_DEG  # noqa: E402

SLIP_DEG = 1.0
DMAX = 0.95 * X_HIDDEN
GP = grid_points()


def touching_points(pad_dz=0.0, half_height=None, radius=None, tol=5e-5):
    """Pad points (x, z, pad frame) that carry load. Box: |z + dz| <= half_height. Cylinder (axis along x, dz below
    the pad centre): only points within tol of the first one the closing fingers meet."""
    z_obj = GP[:, 1] + pad_dz                              # point heights relative to the object centre line
    if radius is None:
        keep = np.ones(len(GP), bool) if half_height is None else np.abs(z_obj) <= half_height
        return GP[keep]
    reach = np.sqrt(np.clip(radius**2 - z_obj**2, 0, None))
    return GP[reach >= reach.max() - tol]


CASES = [  # (name, rig options, prediction points, cos(tilt), lift (h, T), note)
    ("reference (box 20x4x4 cm)", {}, GP, 1.0, None, ""),
    ("box yawed 3 deg", dict(yaw_deg=3.0), GP, 1.0, None, "fingers not square to the face"),
    ("box yawed 10 deg", dict(yaw_deg=10.0), GP, 1.0, None, "fingers not square to the face"),
    ("grasp +1 cm toward the weight", dict(offset=(0.01, 0, 0)), GP, 1.0, None, "predicted: onset + 1 cm"),
    ("grasp -1 cm away from the weight", dict(offset=(-0.01, 0, 0)), GP, 1.0, None, "predicted: onset - 1 cm"),
    ("grasp 8 mm off-centre sideways", dict(offset=(0, 0.008, 0)), GP, 1.0, None, "one finger touches first"),
    ("grasp 5 mm high on the face", dict(offset=(0, 0, 0.005)), GP, 1.0, None, "patch still fully on the face"),
    ("thin box (1 cm tall)", dict(size=(0.10, 0.02, 0.005)), touching_points(half_height=0.005), 1.0, None,
     "only the two middle rows touch"),
    ("cylinder r 2 cm, through the axis", dict(shape="cylinder", size=(0.10, 0.02)), touching_points(radius=0.02),
     1.0, None, "line contact: two middle rows"),
    ("cylinder r 2 cm, pad 5 mm above axis", dict(shape="cylinder", size=(0.10, 0.02), offset=(0, 0, 0.005)),
     touching_points(0.005, radius=0.02), 1.0, None, "one row, contact normal tilted 4 deg"),
    ("cylinder r 2 cm, pad 10 mm above axis", dict(shape="cylinder", size=(0.10, 0.02), offset=(0, 0, 0.010)),
     touching_points(0.010, radius=0.02), 1.0, None, "one row, contact normal tilted 10 deg; squeezed downward"),
    ("mid-air grasp, closing axis level", dict(midair=True), GP, 1.0, None, "reference for the tilted cases"),
    ("mid-air, closing axis tilted 15 deg", dict(midair=True, roll_deg=15.0), GP, np.cos(np.radians(15)), None,
     "predicted: weight in the pad plane is W cos(tilt)"),
    ("mid-air, closing axis tilted 30 deg", dict(midair=True, roll_deg=30.0), GP, np.cos(np.radians(30)), None,
     "the D3 limit"),
    ("fast lift (10 cm in 0.6 s)", {}, GP, 1.0, (LIFT_H, 0.6), "peak acceleration 1.6 m/s^2"),
    ("slow lift (10 cm in 2.4 s)", {}, GP, 1.0, (LIFT_H, 2.4), "peak acceleration 0.10 m/s^2"),
    ("time step 1 ms", dict(timestep=0.001), GP, 1.0, None, "numerical check"),
]


def write_tex(rows, out, contact):
    """LaTeX rows: case, points, band, 1-deg onset (deviation), 10-deg failure (deviation); dagger = outside band."""
    def cell(x, flag, ok, p0, shift):
        if flag != "ok":
            return {"never": "never", "always": "at $d{=}0$", "non-monotone": "n/m"}.get(flag, flag)
        return f"{x*100:.2f} ({(x-p0)/(p0-shift)*100:+.0f}\\%){'' if ok else '$^\\dagger$'}"
    with open(out / f"characterize_{contact}.tex", "w") as f:
        f.write("% generated by scripts/characterize_contact.py -- do not edit\n")
        f.write("\\newcommand{\\calibcharacterize" + contact + "}{%\n")
        for r in rows:
            p0, p1 = float(r["pred_static"]), float(r["pred_peak"])
            shift = float(r.get("shift", 0) or 0)
            tol = float(r.get("tol", 0.0855 / 8 / 64))
            s1, s10 = float(r["slip"]), float(r["fail10"])
            ok1 = r["slip_flag"] == "ok" and p1 - tol <= s1 <= p0 + tol
            ok10 = r["fail_flag"] == "ok" and p1 - tol <= s10 <= p0 + tol
            f.write(f"{r['case']} & {r['points']} & {p1*100:.2f}--{p0*100:.2f} & "
                    f"{cell(s1, r['slip_flag'], ok1, p0, shift)} & {cell(s10, r['fail_flag'], ok10, p0, shift)} \\\\\n")
        f.write("}\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--contact", choices=("rubber", "rigid"), default="rubber")
    ap.add_argument("--iters", type=int, default=6)
    ap.add_argument("--tex-only", action="store_true", help="rebuild the table from the saved CSV")
    args = ap.parse_args()
    if args.tex_only:
        out = ROOT / "results" / "calib"
        rows = list(csv.DictReader(open(out / f"characterize_{args.contact}.csv")))
        for r in rows:
            r["shift"] = 0.01 if r["case"].startswith("grasp +1") else (-0.01 if r["case"].startswith("grasp -1") else 0.0)
        write_tex(rows, out, args.contact)
        print("rebuilt table")
        return
    contact = CONTACT if args.contact == "rubber" else RIGID_CONTACT
    out = ROOT / "results" / "calib"
    out.mkdir(parents=True, exist_ok=True)
    rows = []
    for name, rig, pts, ctilt, lift, note in CASES:
        lift_h, lift_t = lift if lift else (LIFT_H, LIFT_T)
        m_eff = MASS * ctilt                                  # only W cos(tilt) lies in the pad plane
        p0 = patch_dstar(pts, m=m_eff)
        p1 = patch_dstar(pts, m=m_eff, accel=a_peak(lift_h, lift_t))
        shift = rig.get("offset", (0, 0, 0))[0]               # grasp moved along the long axis moves the onset
        p0, p1 = p0 + shift, p1 + shift
        kw = dict(pads="grid", contact=contact, lift_h=lift_h, lift_t=lift_t, **rig)
        slip, f1 = bisect_onset(DMAX, iters=args.iters, twist_deg=SLIP_DEG, **kw)
        fail, f2 = bisect_onset(DMAX, iters=args.iters, twist_deg=TWIST_DEG, **kw)
        tol = DMAX / 8 / 2**args.iters
        ok = f1 == "ok" and p1 - tol <= slip <= p0 + tol
        dev = (slip - p0) / (p0 - shift) * 100 if f1 == "ok" else np.nan
        rows.append(dict(case=name, points=len(pts), pred_peak=p1, pred_static=p0, slip=slip, slip_flag=f1,
                         fail10=fail, fail_flag=f2, in_band=ok, dev_pct=dev, note=note, shift=shift, tol=tol))
        print(f"{name:40s} pts {len(pts):2d}  band {p1*100:5.2f}-{p0*100:5.2f}  slip {slip*100:6.2f} [{f1}] "
              f"{'in band' if ok else f'{dev:+5.1f}% vs static'}   10-deg failure {fail*100:6.2f} [{f2}]", flush=True)
    with open(out / f"characterize_{args.contact}.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    write_tex(rows, out, args.contact)
    print(f"saved {out}/characterize_{args.contact}.csv/.tex")


if __name__ == "__main__":
    main()
